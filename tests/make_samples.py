# -*- coding: utf-8 -*-
"""构造三类测试样本，用于验证检测器各路信号与融合决策的正确性。

ai_like     —— 模拟生成图特征：512x512 PNG、最近邻上采样（产生 2px 网格伪影）、
               异常平滑（低噪声 + 轻高斯模糊）、无任何 EXIF。
real_like   —— 模拟真实照片特征：非规则尺寸 JPEG、丰富纹理 + 传感器级噪声、
               完整相机 EXIF（Make / Model / DateTime）。
ai_tagged   —— ai_like 之上追加含 "Stable Diffusion" 的 XMP 字节（PNG 规范允许
               文件尾附加数据，字节级扫描可命中），验证元数据确定性短路。
"""

from __future__ import annotations

import sys
from pathlib import Path

import cv2
import numpy as np
from PIL import Image

OUT = Path(__file__).resolve().parent / "samples"
RNG = np.random.default_rng(42)


def make_ai_like(path: Path, seed: int) -> Path:
    rng = np.random.default_rng(seed)
    yy, xx = np.mgrid[0:256, 0:256].astype(np.float32)
    content = 128.0 + 40.0 * np.sin(xx / 31.0) + 30.0 * np.cos(yy / 27.0)
    content += 20.0 * np.sin((xx + yy) / 47.0)
    # 最近邻 2x 上采样：模拟 latent 到像素的分辨率提升。
    img = cv2.resize(content, (512, 512), interpolation=cv2.INTER_NEAREST)
    img += rng.normal(0.0, 0.8, img.shape).astype(np.float32)   # 异常平滑：极低噪声
    img = cv2.GaussianBlur(img, (3, 3), 0.5)                    # 扩散输出的整体平滑感
    # 2px 棋盘伪影（±1.5 灰度级）：模拟转置卷积解码器的 checkerboard
    # artifact（Odena et al., 2016），频谱特征为奈奎斯特角窗尖峰。
    X, Y = np.mgrid[0:512, 0:512].astype(np.float32)
    checker = ((X + Y) % 2).astype(np.float32) - 0.5   # 2px 对角棋盘，恒定于目标网格
    img += checker * 3.0
    Image.fromarray(np.clip(img, 0, 255).astype(np.uint8), "L").save(path, format="PNG")
    return path


def make_real_like(path: Path, seed: int) -> Path:
    rng = np.random.default_rng(seed)
    img = RNG.normal(118.0, 26.0, (900, 1200)).astype(np.float32)   # 纹理基底
    for _ in range(12):                                             # 平滑物体区域
        cx, cy, r = rng.integers(100, 1100), rng.integers(100, 800), rng.integers(60, 220)
        val = rng.uniform(60, 200)
        cv2.circle(img, (int(cx), int(cy)), int(r), float(val), -1)
    img = cv2.GaussianBlur(img, (5, 5), 1.2)
    img += rng.normal(0.0, 3.0, img.shape).astype(np.float32)       # 传感器级噪声
    pil = Image.fromarray(np.clip(img, 0, 255).astype(np.uint8), "L")
    exif = Image.Exif()
    exif[271] = "Canon"
    exif[272] = "Canon EOS R6"
    exif[306] = "2026:01:15 10:30:00"
    pil.save(path, format="JPEG", quality=90, exif=exif.tobytes())
    return path


def make_ai_tagged(path: Path, seed: int) -> Path:
    make_ai_like(path, seed)
    xmp = (
        b"\n<?xpacket begin='' id='W5M0MpCehiHzreSzNTczkc9d'?>\n"
        b'<x:xmpmeta xmlns:x="adobe:ns:meta/"><rdf:RDF>'
        b'<rdf:Description dc:description="generated by Stable Diffusion"/>'
        b"</rdf:RDF></x:xmpmeta>\n<?xpacket end='w'?>\n"
    )
    with open(path, "ab") as f:
        f.write(xmp)
    return path


def generate_all(out_dir: Path = OUT) -> dict:
    out_dir.mkdir(parents=True, exist_ok=True)
    made = {"ai_like": [], "real_like": [], "ai_tagged": []}
    for i in range(5):
        made["ai_like"].append(str(make_ai_like(out_dir / ("ai_like_%03d.png" % i), seed=100 + i)))
        made["real_like"].append(str(make_real_like(out_dir / ("real_like_%03d.jpg" % i), seed=200 + i)))
        made["ai_tagged"].append(str(make_ai_tagged(out_dir / ("ai_tagged_%03d.png" % i), seed=300 + i)))
    return made


if __name__ == "__main__":
    result = generate_all(Path(sys.argv[1]) if len(sys.argv) > 1 else OUT)
    for kind, paths in result.items():
        print("%s: %d 个样本" % (kind, len(paths)))
